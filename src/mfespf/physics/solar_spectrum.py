def hsrs_cumulative(wavelength_m: np.ndarray) -> np.ndarray:
    """Irradiance at 1 au shortward of each wavelength, W m^-2.

    Zero below the spectrum's short end and the full integral above its long
    end: the spectrum is measured, and nothing is invented outside it.
    """
    nm = np.asarray(wavelength_m, dtype=float) * 1.0e9
    return np.interp(nm, _NODES_NM, _CUMULATIVE_W_M2, left=0.0, right=HSRS_TOTAL_W_M2)


def hsrs_band_irradiance(edges_m: np.ndarray) -> np.ndarray:
    """Irradiance at 1 au in each band between consecutive edges, W m^-2."""
    return np.diff(hsrs_cumulative(np.asarray(edges_m, dtype=float)))
