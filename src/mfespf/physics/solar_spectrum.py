"""The measured solar spectrum: TSIS-1 HSRS version 2, reduced.

Why this exists
---------------

The solar source's spectral shape was a 5772 K black body. It puts 12.1 percent
of the sunlight between 0.175 and 0.4 microns, where the real spectrum carries
8.0 percent (Chou and Suarez 1999, Table 3), and ozone's heating is mostly
there. A mechanism that absorbs in the ultraviolet needs the ultraviolet the sun
actually emits (``docs/protocols/ozone-solar-heating.md``).

Where the numbers come from
---------------------------

Coddington, O. M., et al. (2023), *Version 2 of the TSIS-1 Hybrid Solar
Reference Spectrum and Extension to the Full Spectrum*, Earth and Space Science
10, doi:10.1029/2022EA002637. The full-spectrum product, 1 nm bins from 115.5 nm
to 200 microns, LASP LISIRD dataset ``tsis1_hsrs_binned_fs``, integrates to
1361.4892 W m^-2. That file is declared in ``data/sources.yaml`` (SHA-256
``e63693db...``); it is not committed, for the reason ``data/README.md`` gives.

What is committed is its cumulative irradiance at 1497 wavelengths in
0.5 percent logarithmic steps, each bin taken as uniform over its 1 nm. Band
integrals on any grid come from differences of this cumulative, interpolated
linearly. Measured against the full file, that reduction is within 0.25 percent
on the narrowest ozone band (225-245 nm) and within 0.01 percent on bands 0.3
microns and wider.
"""

